"""Reads the code colors from each theme that ships with Notepad++ and writes src/syntax_colors.rs.

For every theme, z++ takes seven token colors (comment, keyword, type, string, number, operator,
preprocessor) from the theme's C++ styles, plus bold and italic. Notepad++'s own default styles
(stylers.model.xml) give the colors for z++'s Light theme. Only color and font-style values are
used; no theme file is copied.

Run: uv run --with defusedxml python scripts/import_npp_syntax.py
"""

import json
import pathlib
import urllib.request

from defusedxml import ElementTree

REPO_API = "https://api.github.com/repos/notepad-plus-plus/notepad-plus-plus/contents/PowerEditor/installer/themes"
RAW = "https://raw.githubusercontent.com/notepad-plus-plus/notepad-plus-plus/master/PowerEditor/"
DEFAULT_STYLES = RAW + "src/stylers.model.xml"
OUT = pathlib.Path(__file__).resolve().parent.parent / "src" / "syntax_colors.rs"

# Same display names as scripts/import_npp_themes.py.
DISPLAY_NAMES = {
    "DansLeRuSH-Dark": "DansLeRuSH Dark",
    "DarkModeDefault": "Dark Mode Default",
    "HotFudgeSundae": "Hot Fudge Sundae",
    "MossyLawn": "Mossy Lawn",
    "Solarized-light": "Solarized Light",
    "Solarized": "Solarized Dark",
    "khaki": "Khaki",
    "vim Dark Blue": "Vim Dark Blue",
}

# Token field in themes::Syntax -> Notepad++ C++ style ID (Lexilla SCE_C_*).
TOKENS = [
    ("comment", "1"),
    ("keyword", "5"),
    ("kind", "16"),
    ("string", "6"),
    ("number", "4"),
    ("operator", "10"),
    ("preprocessor", "9"),
]


def fetch(url: str) -> bytes:
    with urllib.request.urlopen(url, timeout=30) as resp:
        return resp.read()


def cpp_styles(xml: bytes) -> dict[str, tuple[str, int]]:
    root = ElementTree.fromstring(xml)
    for lexer in root.iter("LexerType"):
        if lexer.get("name") == "cpp":
            return {
                s.get("styleID"): (s.get("fgColor"), int(s.get("fontStyle") or 0))
                for s in lexer.iter("WordsStyle")
            }
    raise ValueError("no cpp styles")


def rust_entry(name: str, styles: dict[str, tuple[str, int]]) -> str:
    fields = []
    for field, style_id in TOKENS:
        fg, font_style = styles[style_id]
        fields.append(f"        {field}: tok(0x{fg.upper()}, {font_style & 3}),")
    body = "\n".join(fields)
    return f'    (\n        "{name}",\n        Syntax {{\n{body}\n        }},\n    ),'


def main() -> None:
    entries = [rust_entry("Light", cpp_styles(fetch(DEFAULT_STYLES)))]
    files = [f["name"] for f in json.loads(fetch(REPO_API)) if f["name"].endswith(".xml")]
    for name in sorted(files, key=str.lower):
        stem = name[: -len(".xml")]
        styles = cpp_styles(fetch(RAW + "installer/themes/" + urllib.request.quote(name)))
        entries.append(rust_entry(DISPLAY_NAMES.get(stem, stem), styles))
    header = (
        "//! Generated by scripts/import_npp_syntax.py: code colors from the theme files that ship\n"
        "//! with Notepad++, and Notepad++'s default styles for Light. Do not edit by hand.\n\n"
        "use crate::themes::{tok, Syntax};\n\n"
        "pub const NPP_SYNTAX: &[(&str, Syntax)] = &[\n"
    )
    OUT.write_text(header + "\n".join(entries) + "\n];\n", encoding="utf-8", newline="\n")
    print(f"wrote {len(entries)} themes to {OUT}")


if __name__ == "__main__":
    main()
